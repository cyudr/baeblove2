-- Supabase Postgres schema for "entries", "growth", and "routine" tables.
-- Run this SQL in your Supabase SQL Editor if any table or realtime publication is not yet enabled.

-- 1. Core app state table: "entries"
create table if not exists public.entries (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  profile_id text not null default ''::text,
  payload json,
  updated_at timestamptz not null default now()
);

create index if not exists entries_profile_id_idx on public.entries (profile_id);

-- 2. Daily growth & vitals table: "growth"
-- `profile_id` matches the active profile in `entries`; `name` stores the person logging the data.
create table if not exists public.growth (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  profile_id text not null default ''::text,
  daily_weight real,
  daily_length real,
  temperature real,
  remark varchar,
  name varchar
);

alter table public.growth add column if not exists profile_id text not null default ''::text;
create index if not exists growth_profile_id_idx on public.growth (profile_id);

-- 3. Daily feeding & diaper routine table: "routine"
-- `profile_id` matches the active profile in `entries`; `name` stores the person logging the data.
create table if not exists public.routine (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  profile_id text not null default ''::text,
  date date,
  time time,
  "EBM (mL)" integer,
  "Formula (mL)" integer,
  "Diaper" varchar,
  name varchar,
  remark varchar,
  "feed duration (min)" integer
);

alter table public.routine add column if not exists profile_id text not null default ''::text;
create index if not exists routine_profile_id_idx on public.routine (profile_id);

-- Ensure full row data is included on DELETE events in Supabase Realtime
alter table public.entries replica identity full;
alter table public.growth replica identity full;
alter table public.routine replica identity full;

-- Add tables to the supabase_realtime publication for .channel().on('postgres_changes', ...)
do $$
declare
  tbl text;
begin
  foreach tbl in array array['entries', 'growth', 'routine'] loop
    if not exists (
      select 1
      from pg_publication_tables
      where pubname = 'supabase_realtime'
        and schemaname = 'public'
        and tablename = tbl
    ) then
      execute format('alter publication supabase_realtime add table public.%I', tbl);
    end if;
  end loop;
end $$;

-- Row Level Security policies (adjust to match your auth model)
alter table public.entries enable row level security;
alter table public.growth enable row level security;
alter table public.routine enable row level security;

do $$
declare
  tbl text;
begin
  foreach tbl in array array['entries', 'growth', 'routine'] loop
    if not exists (
      select 1 from pg_policies where schemaname = 'public' and tablename = tbl and policyname = 'Allow read access'
    ) then
      execute format('create policy "Allow read access" on public.%I for select using (true)', tbl);
    end if;
    if not exists (
      select 1 from pg_policies where schemaname = 'public' and tablename = tbl and policyname = 'Allow insert access'
    ) then
      execute format('create policy "Allow insert access" on public.%I for insert with check (true)', tbl);
    end if;
    if not exists (
      select 1 from pg_policies where schemaname = 'public' and tablename = tbl and policyname = 'Allow update access'
    ) then
      execute format('create policy "Allow update access" on public.%I for update using (true) with check (true)', tbl);
    end if;
    if not exists (
      select 1 from pg_policies where schemaname = 'public' and tablename = tbl and policyname = 'Allow delete access'
    ) then
      execute format('create policy "Allow delete access" on public.%I for delete using (true)', tbl);
    end if;
  end loop;
end $$;
